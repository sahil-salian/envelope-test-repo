# envelope:control art50.disclosure v1
"""AI interaction disclosure (EU AI Act Article 50(1)).

Show this at the start of every conversation unless it is obvious the user is talking to AI.
"""

AI_DISCLOSURE = "You are chatting with an AI assistant. Its replies are generated by AI and may be inaccurate."


def with_ai_disclosure(text: str) -> str:
    """Prefix the first assistant message with the disclosure (idempotent)."""
    return text if text.startswith(AI_DISCLOSURE) else f"{AI_DISCLOSURE}\n\n{text}"
